"""Check that every hand-written number in README.md and MODEL_CARD.md matches
what the code produces. The results block between the RESULTS markers is
generated by evaluate.py and needs no check; this covers everything else.

Run after leakage_audit.py, build_scorecard.py and evaluate.py (run_eval.py
does this). Exits non-zero on any mismatch.
"""
import json
import sys

import numpy as np
import pandas as pd

import credit_data as cd
import pd_model as pm

readme = open("README.md", encoding="utf-8").read()
card = open("MODEL_CARD.md", encoding="utf-8").read()
docs = readme + card
checks = []


def expect(label, text, computed, where=docs):
    checks.append((label, text, computed, text in where and text == computed))


# ---- data facts, recomputed from the raw files ---------------------------------
raw = pd.read_csv(cd.RAW)
clean = pd.read_csv(cd.CLEAN)
X, y, rep = cd.load_raw()
expect("raw rows", "32,581", f"{len(raw):,}")
expect("rows after dedup", "32,416", f"{rep['rows_final']:,}")
expect("duplicates removed", "165", str(rep["duplicates_removed"]))
expect("impossible values nulled", "7 impossible values", f"{rep['cells_nulled']} impossible values")
for col, txt in (("person_emp_length", "895"), ("loan_int_rate", "3,114")):
    n = int(clean[col].sub(raw[col].mean()).abs().lt(1e-6).sum())
    expect(f"{col} rows at full-data mean", txt, f"{n:,}")
feat = [c for c in raw.columns if c != cd.TARGET]
key = pd.util.hash_pandas_object(raw[feat], index=False)
from sklearn.model_selection import StratifiedKFold
spill = [int(key.iloc[te].isin(set(key.iloc[tr])).sum())
         for tr, te in StratifiedKFold(5, shuffle=True, random_state=cd.RANDOM_STATE).split(raw, raw[cd.TARGET])]
expect("duplicate spill per fold", "~51.6", f"~{np.mean(spill):.1f}")
g = pd.DataFrame({"g": X.loan_grade, "y": y}).groupby("g").y.mean()
expect("grade G default rate", "98.4%", f"{g['G']*100:.1f}%")
expect("missing rates filled for accounting", "3,095 loans", f"{int(X.loan_int_rate.isna().sum()):,} loans")
expect("model features", "Features used (10)", f"Features used ({pm.select(X).shape[1]})", card)

# ---- leakage ablation ----------------------------------------------------------
ab = pd.read_csv("reports/leakage_ablation.csv")
for _, r in ab.iterrows():
    expect(f"ablation {r.Configuration} {r.Model}",
           f"{r['CV ROC-AUC']:.4f} ± {r['CV Std']:.4f} | {r.KS:.4f}",
           f"{r['CV ROC-AUC']:.4f} ± {r['CV Std']:.4f} | {r.KS:.4f}")
rf = ab[ab.Model == "Random Forest"].reset_index(drop=True)
expect("finding 1", f"from {rf.loc[0,'CV ROC-AUC']:.4f} to {rf.loc[2,'CV ROC-AUC']:.4f}",
       f"from {rf.loc[0,'CV ROC-AUC']:.4f} to {rf.loc[2,'CV ROC-AUC']:.4f}")
expect("finding 1 noise", f"±{rf.loc[2,'CV Std']:.4f} fold noise", f"±{rf.loc[2,'CV Std']:.4f} fold noise")
expect("app-only drop", f"falls from {rf.loc[2,'CV ROC-AUC']:.4f} to {rf.loc[3,'CV ROC-AUC']:.4f}",
       f"falls from {rf.loc[2,'CV ROC-AUC']:.4f} to {rf.loc[3,'CV ROC-AUC']:.4f}")

# ---- scorecard ------------------------------------------------------------------
sm = json.load(open("reports/scorecard_meta.json"))
iv = pd.read_csv("reports/iv_table.csv")
expect("scorecard AUC", f"**{sm['cv_auc']:.4f} ± {sm['cv_std']:.4f}**", f"**{sm['cv_auc']:.4f} ± {sm['cv_std']:.4f}**")
expect("scorecard KS", f"KS **{sm['ks']:.4f}**", f"KS **{sm['ks']:.4f}**")
for _, r in iv.head(3).iterrows():
    expect(f"IV {r.Feature}", f"`{r.Feature}` {r.IV:.4f}", f"`{r.Feature}` {r.IV:.4f}")

# ---- evaluate.py outputs referenced in prose -------------------------------------
mm = pd.read_csv("reports/model_metrics.csv")
raw_bal = mm[(mm.Variant == "raw") & mm.Model.isin(
    ["Logistic Regression", "Random Forest", "LightGBM (all features)", "LightGBM deployed (excl. age)"])]
over = (raw_bal["Mean PD"] / y.mean() - 1) * 100
expect("over-prediction range", f"by {over.min():.0f}–{over.max():.0f}%", f"by {over.min():.0f}–{over.max():.0f}%")
dep = mm[(mm.Model == "LightGBM deployed (excl. age)") & (mm.Variant == "calibrated")].iloc[0]
sca = mm[(mm.Model == "WoE Scorecard") & (mm.Variant == "calibrated")].iloc[0]
expect("scorecard AUC cost", f"about {dep['ROC-AUC'] - sca['ROC-AUC']:.3f} ROC-AUC",
       f"about {dep['ROC-AUC'] - sca['ROC-AUC']:.3f} ROC-AUC")
lg_all = mm[(mm.Model == "LightGBM (all features)") & (mm.Variant == "raw")].iloc[0]
lg_dep = mm[(mm.Model == "LightGBM deployed (excl. age)") & (mm.Variant == "raw")].iloc[0]
expect("age exclusion cost", f"costs about {lg_all['ROC-AUC'] - lg_dep['ROC-AUC']:.3f} ROC-AUC",
       f"costs about {lg_all['ROC-AUC'] - lg_dep['ROC-AUC']:.3f} ROC-AUC", card)
fair = pd.read_csv("reports/fairness_age.csv")
expect("56+ band size", f"(n = {int(fair[fair.band == '56+'].Applicants.iloc[0])})",
       f"(n = {int(fair[fair.band == '56+'].Applicants.iloc[0])})")
pol = pd.read_csv("reports/policy_comparison.csv").set_index("Policy")["Realised profit"]
old = pol[[i for i in pol.index if i.startswith("Old app")][0]]
new = pol[[i for i in pol.index if i.startswith("Deployed")][0]]
gap = abs(new - old) / abs(old)
expect("deployed vs old profit gap", "slightly *less* realised profit than the old uncalibrated 0.50 cut-off — within 1%",
       ("slightly *less*" if new < old else "MORE") + " realised profit than the old uncalibrated 0.50 cut-off — " + ("within 1%" if gap < 0.01 else f"{gap:.1%} apart"))
expect("PD floor", "0.03%", f"{pm.PD_FLOOR*100:.2f}%")
expect("LGD", "45%", f"{pm.LGD*100:.0f}%")

bad = [c for c in checks if not c[3]]
for label, text, computed, ok in checks:
    print(f"  [{'OK ' if ok else 'BAD'}] {label}: docs say {text!r}, code gives {computed!r}")
print(f"\n{len(checks) - len(bad)}/{len(checks)} hand-written numbers verified")
sys.exit(1 if bad else 0)
